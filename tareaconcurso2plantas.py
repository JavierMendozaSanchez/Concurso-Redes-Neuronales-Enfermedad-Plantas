class MLflowEpochLogger(Callback):
    def __init__(self, run_id=None, log_every_n_epochs=1, plot_every_n_epochs=5):
        super().__init__()
        self.log_every_n_epochs = log_every_n_epochs
        self.plot_every_n_epochs = plot_every_n_epochs
        self.history = {
            'loss': [], 'val_loss': [], 'accuracy': [], 'val_accuracy': []
        }
        self.run_id = run_id

    def on_epoch_end(self, epoch, logs=None):
        logs = logs or {}

        # se actualiza el historial (solo train y val)
        for k in ['loss', 'val_loss', 'accuracy', 'val_accuracy']:
            if k in logs:
                self.history[k].append(float(logs[k]))

        # registramos las metricas
        if (epoch + 1) % self.log_every_n_epochs == 0:
            for k, v in logs.items():
                try:
                    mlflow.log_metric(k, float(v), step=epoch)
                except Exception as e:
                    print("Warning mlflow.log_metric:", e)

        # subimos las graficas cada 5 épocas
        if (epoch + 1) % self.plot_every_n_epochs == 0:
            try:
                epochs_range = range(1, len(self.history['loss']) + 1)

                # graficas de loss
                fig, ax = plt.subplots(figsize=(10, 6))
                ax.plot(epochs_range, self.history['loss'], label='Train Loss', linewidth=2)
                ax.plot(epochs_range, self.history['val_loss'], label='Val Loss', linewidth=2)
                ax.set_xlabel('Época')
                ax.set_ylabel('Loss')
                ax.set_title('Evolución del Loss')
                ax.legend()
                ax.grid(True, alpha=0.3)
                loss_img = f'loss_epoch_{epoch+1}.png'
                fig.savefig(loss_img, dpi=100, bbox_inches='tight')
                plt.close(fig)
                mlflow.log_artifact(loss_img, artifact_path="plots")
                os.remove(loss_img)

                # las del acuaracy
                fig, ax = plt.subplots(figsize=(10, 6))
                ax.plot(epochs_range, self.history['accuracy'], label='Train Accuracy', linewidth=2)
                ax.plot(epochs_range, self.history['val_accuracy'], label='Val Accuracy', linewidth=2)
                ax.set_xlabel('Época')
                ax.set_ylabel('Accuracy')
                ax.set_title('Evolución del Accuracy')
                ax.legend()
                ax.grid(True, alpha=0.3)
                acc_img = f'acc_epoch_{epoch+1}.png'
                fig.savefig(acc_img, dpi=100, bbox_inches='tight')
                plt.close(fig)
                mlflow.log_artifact(acc_img, artifact_path="plots")
                os.remove(acc_img)

                print(f" Gráficas (Train/Val) subidas a MLflow (Época {epoch+1})")

            except Exception as e:
                print("Warning al crear/logear plots:", e)

print("Logger de gráficas de MLflow (Loss/Accuracy) creado.")

