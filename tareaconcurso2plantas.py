def cargar_datos_y_crear_estructura():

    # cargamos train.csv
    print(" Cargando train.csv...")
    if not os.path.exists(TRAIN_CSV_PATH):
        print(f"ERROR: No se encuentra {TRAIN_CSV_PATH}")
        return None, None, None, 0, 0

    train_df = pd.read_csv(TRAIN_CSV_PATH)

    # verificamos la estructura
    clases = ['healthy', 'multiple_diseases', 'rust', 'scab']
    print(" Distribución de clases:")
    for clase in clases:
        count = train_df[clase].sum()
        print(f"   {clase}: {count} imágenes ({count/len(train_df)*100:.1f}%)")

    # la divicion de datos sera (70% train, 30% test)
    print("\n Dividiendo datos...")
    train_data, test_data = train_test_split(
        train_df,
        test_size=0.3,
        random_state=42,
        stratify=train_df[clases].values.argmax(axis=1)
    )

    print(f" Datos de entrenamiento: {len(train_data)} imágenes")
    print(f" Datos de test: {len(test_data)} imágenes")

    # se crea la estructura de directorios
    print("\n Creando estructura de directorios...")
    base_temp_path = "/content/plant_pathology_structured"

    # se limpia el directorio temporal si existe
    if os.path.exists(base_temp_path):
        shutil.rmtree(base_temp_path)

    # creamos los directorios
    train_dir = os.path.join(base_temp_path, "train")
    test_dir = os.path.join(base_temp_path, "test")

    os.makedirs(train_dir, exist_ok=True)
    os.makedirs(test_dir, exist_ok=True)

    # hacemos los mismo con los subdirectorios
    for clase in clases:
        os.makedirs(os.path.join(train_dir, clase), exist_ok=True)
        os.makedirs(os.path.join(test_dir, clase), exist_ok=True)

    # esta funcion es para copiar las images
    def copiar_imagenes(dataframe, target_dir, dataset_type):
        copied_count = 0
        for idx, row in dataframe.iterrows():
            image_id = row['image_id']
            source_path = os.path.join(IMAGES_PATH, f"{image_id}.jpg")

            # se determina la clase
            for clase in clases:
                if row[clase] == 1:
                    target_path = os.path.join(target_dir, clase, f"{image_id}.jpg")
                    if os.path.exists(source_path):
                        shutil.copy2(source_path, target_path)
                        copied_count += 1
                    break

        print(f"   - {dataset_type}: {copied_count} imágenes copiadas")
        return copied_count

    # copiamos las imagenes
    print(" Copiando imágenes de entrenamiento...")
    train_count = copiar_imagenes(train_data, train_dir, "Train")

    print(" Copiando imágenes de test...")
    test_count = copiar_imagenes(test_data, test_dir, "Test")

    print(f" Estructura creada: {train_count + test_count} imágenes totales")

    return train_dir, test_dir, clases, len(train_data), len(test_data)

