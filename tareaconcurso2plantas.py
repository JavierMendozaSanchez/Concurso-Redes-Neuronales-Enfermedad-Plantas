def create_model_from_trial_categorical(trial):
    """Crear modelo con clasificación categórica"""

    # hiperparametros
    unfreeze_layers = trial.suggest_int("unfreeze_layers", 10, 100)
    dropout_rate = trial.suggest_float("dropout", 0.1, 0.5)

    # base preentrenada
    base_model = EfficientNetB2(
        weights='imagenet',
        include_top=False,
        input_shape=(256, 256, 3)
    )

    #congelamos capas
    base_model.trainable = True
    for layer in base_model.layers[:-unfreeze_layers]:
        layer.trainable = False

    # se construye el modelo
    inputs = tf.keras.Input(shape=(256, 256, 3))
    x = base_model(inputs, training=True)
    x = layers.GlobalAveragePooling2D()(x)

    n_dense_layers = trial.suggest_int("n_dense_layers", 1, 3)
    for i in range(n_dense_layers):
        units = trial.suggest_int(f"dense_units_{i}", 64, 512, log=True)

        #orden a seguir
        x = layers.Dense(units, use_bias=False)(x)
        x = layers.BatchNormalization()(x)
        x = layers.Activation('relu')(x)
        x = layers.Dropout(dropout_rate)(x)

    # capa de salida usando softmax
    outputs = layers.Dense(num_classes, activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs)

    # optimizador
    lr = trial.suggest_float("lr", 1e-5, 1e-3, log=True)
    optimizer_name = trial.suggest_categorical("optimizer", ["adam", "rmsprop"])

    if optimizer_name == "adam":
        optimizer = optimizers.Adam(learning_rate=lr)
    else:
        optimizer = optimizers.RMSprop(learning_rate=lr)

    #hacemos la compilacion con categorical cross entropy
    model.compile(
        optimizer=optimizer,
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )

    return model, base_model

