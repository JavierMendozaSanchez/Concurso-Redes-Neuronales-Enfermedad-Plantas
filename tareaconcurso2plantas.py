def crear_generadores_finales(train_dir, test_dir, img_size=(256, 256), batch_size=32):


    print(" Creando generadores con flow_from_directory...")
#usamos estos rangos
    train_datagen = ImageDataGenerator(
        rotation_range=20,
        width_shift_range=0.2,
        height_shift_range=0.2,
        horizontal_flip=True,
        zoom_range=0.2,
        brightness_range=[0.8, 1.2],
        validation_split=0.2
    )

    test_datagen = ImageDataGenerator()

    train_generator = train_datagen.flow_from_directory(
        train_dir,
        target_size=img_size,
        batch_size=batch_size,
        class_mode='categorical',
        subset='training',
        shuffle=True
    )

    val_generator = train_datagen.flow_from_directory(
        train_dir,
        target_size=img_size,
        batch_size=batch_size,
        class_mode='categorical',
        subset='validation',
        shuffle=False
    )

    test_generator = test_datagen.flow_from_directory(
        test_dir,
        target_size=img_size,
        batch_size=batch_size,
        class_mode='categorical',
        shuffle=False
    )
    print(" Generadores creados CORRECTAMENTE")
    print(f"   - Training: {train_generator.samples} imágenes")
    print(f"   - Validation: {val_generator.samples} imágenes")
    print(f"   - Test: {test_generator.samples} imágenes")
    print(f"   - Clases: {train_generator.class_indices}")

    return train_generator, val_generator, test_generator

