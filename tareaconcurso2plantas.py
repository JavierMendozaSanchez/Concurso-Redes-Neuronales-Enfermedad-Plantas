def objective(trial):

    try:
        with mlflow.start_run(nested=True):
            run_id = mlflow.active_run().info.run_id

            #este es el log de hiperparámetros
            model, base_model = create_model_from_trial_categorical(trial)
            trial_params = trial.params
            mlflow.log_params(trial_params)

            # nuestros callbacks
            checkpoint_path = f"best_model_trial_{run_id}.h5"

            checkpoint_cb = ModelCheckpoint(
                checkpoint_path, monitor='val_loss', verbose=0, save_best_only=True, mode='min'
            )
            earlystop_cb = EarlyStopping(
                monitor='val_loss', mode='min', patience=8, restore_best_weights=True, verbose=0
            )
            lr_scheduler_cb = ReduceLROnPlateau(
                monitor='val_loss', factor=0.2, patience=3, verbose=0, min_lr=1e-6
            )
            # --- Logger de gráficas RE-AÑADIDO ---
            mlflow_logger_cb = MLflowEpochLogger(log_every_n_epochs=1, plot_every_n_epochs=5)


            # entrenamiento
            history = model.fit(
                train_gen,
                validation_data=val_gen,
                epochs=20,
                batch_size=BATCH_SIZE,

                callbacks=[checkpoint_cb, earlystop_cb, lr_scheduler_cb, mlflow_logger_cb],
                verbose=0
            )

            # evaluacion final
            val_loss = min(history.history['val_loss'])


            # hacemos el log del mejor modelo
            if os.path.exists(checkpoint_path):
                mlflow.log_artifact(checkpoint_path, artifact_path="models")

            final_val_loss = val_loss

    except Exception as e:
        print(f"Trial falló: {e}")
        final_val_loss = float('inf')

    finally:
        # limpiamos la sesion de keras para liberar memoria
        tf.keras.backend.clear_session()
        del model
        del base_model
        if 'checkpoint_path' in locals() and os.path.exists(checkpoint_path):
            os.remove(checkpoint_path)

    return float(final_val_loss)

