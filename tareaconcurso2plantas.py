def build_final_model_categorical(params):

    print("Construyendo modelo final con parámetros:", params)

    # base preentrenada
    base_model = EfficientNetB2(
        weights='imagenet',
        include_top=False,
        input_shape=(256, 256, 3)
    )

    # configuramos capas preentreables
    unfreeze_layers = params.get("unfreeze_layers", 50)
    base_model.trainable = True
    for layer in base_model.layers[:-unfreeze_layers]:
        layer.trainable = False
    print(f"Capas descongeladas: {unfreeze_layers}")

    # construimos el modelo
    inputs = tf.keras.Input(shape=(256, 256, 3))
    x = base_model(inputs, training=True)
    x = layers.GlobalAveragePooling2D()(x)


    n_dense_layers = params.get("n_dense_layers", 2)
    dropout_rate = params.get("dropout", 0.3)
    print(f"Capas densas: {n_dense_layers}, Dropout: {dropout_rate}")

    for i in range(n_dense_layers):
        units = params.get(f"dense_units_{i}", 256)
        print(f"Capa densa {i} con {int(units)} unidades")


        x = layers.Dense(int(units), use_bias=False)(x)
        x = layers.BatchNormalization()(x)
        x = layers.Activation('relu')(x)
        x = layers.Dropout(float(dropout_rate))(x)


    #nuestra capa de salida sera con softmax
    outputs = layers.Dense(num_classes, activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs)

    # optimizador
    lr = params.get("lr", 1e-4)
    optimizer_name = params.get("optimizer", "adam")
    print(f"Optimizador: {optimizer_name}, LR: {float(lr)}")

    if optimizer_name == "adam":
        optimizer = optimizers.Adam(learning_rate=float(lr))
    else:
        optimizer = optimizers.RMSprop(learning_rate=float(lr))

    # compilamos usando categorical cross entropy
    model.compile(
        optimizer=optimizer,
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )

    return model, base_model

